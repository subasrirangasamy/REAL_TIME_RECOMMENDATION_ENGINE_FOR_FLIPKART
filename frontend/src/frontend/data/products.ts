export function getRecommendations(viewedIds: string[], cartIds: string[]): Product[] {
  const interactedProducts = products.filter(
    (p) => viewedIds.includes(p.id) || cartIds.includes(p.id)
  );
  const interactedCategories = [...new Set(interactedProducts.map((p) => p.category))];
  const interactedTags = [...new Set(interactedProducts.flatMap((p) => p.tags))];

  return products
    .filter((p) => !viewedIds.includes(p.id) && !cartIds.includes(p.id))
    .map((p) => {
      let score = 0;
      if (interactedCategories.includes(p.category)) score += 3;
      p.tags.forEach((t) => { if (interactedTags.includes(t)) score += 1; });
      score += p.rating;
      return { product: p, score };
    })
    .sort((a, b) => b.score - a.score)
    .map((x) => x.product);
}

export function getTrending(): Product[] {
  return [...products].sort((a, b) => b.reviewCount - a.reviewCount).slice(0, 10);
}

export function getDealsOfTheDay(): Product[] {
  return products.filter((p) => {
    const discount = ((p.originalPrice - p.price) / p.originalPrice) * 100;
    return discount >= 20;
  }).sort((a, b) => {
    const dA = ((a.originalPrice - a.price) / a.originalPrice);
    const dB = ((b.originalPrice - b.price) / b.originalPrice);
    return dB - dA;
  }).slice(0, 8);
}

export function getTopRated(): Product[] {
  return [...products].sort((a, b) => b.rating - a.rating).slice(0, 8);
}

export function getBudgetPicks(): Product[] {
  return [...products].filter(p => p.price < 15000).sort((a, b) => b.reviewCount - a.reviewCount).slice(0, 8);
}
